#!/usr/bin/env node
// Turn the IDs of a standard whose text may not be copied into an OSCAL
// catalog: a skeleton with a group per category and series, a control per
// criterion, each with its ID, a title in this repository's own words, and a
// statement that only says where the text is. SOC 2 is the case: the Trust
// Services Criteria are the AICPA's, and a mapping, an assessment plan or a
// result needs nothing of them but the IDs to point at.
//
// Input (JSON), a source file under standards/src/ with "criteria":
//   {
//     "title": "SOC 2 Trust Services Criteria (IDs only)",
//     "version": "TSC 2017, revised points of focus 2022",
//     "last-modified": "2026-10-12T00:00:00Z",
//     "owner": "AICPA",
//     "source": { "title": "2017 Trust Services Criteria ...", "href": "https://..." },
//     "notice": "Whose the text is, and what of it is used here.",
//     "count": 61,                                  // criteria in the source
//     "criteria": [{ "id": "security", "title": "Security (common criteria)",
//                    "groups": [{ "id": "CC1", "title": "Control environment",
//                                 "controls": [["CC1.1", "own short title"], ...] }] }]
//   }
//
// Checked, and an error otherwise:
//   - every ID is an OSCAL token and occurs once
//   - a criterion's ID begins with its series' ID and a dot
//   - the number of criteria is "count", the number the source has
//
// Output: an OSCAL 1.2.3 catalog on stdout. Deterministic: same input, same
// bytes.
//
//   node tools/id-catalog.mjs standards/src/soc2.json > standards/soc2.json
//
// No dependencies. Node 24 (LTS) or later.

import { readFileSync } from "node:fs";
import { NS, uuid5 as uuid5From } from "../lib/oscal.mjs";

const UUID_NS = "7c2e4b19-0a6d-4e83-b5f1-9d3a8c6e2f40";

const file = process.argv[2];
if (!file) {
  console.error("usage: id-catalog.mjs <source.json>");
  process.exit(2);
}
const fail = (msg) => {
  console.error(msg);
  process.exit(1);
};
const src = JSON.parse(readFileSync(file, "utf8"));
for (const k of ["title", "version", "last-modified", "owner", "notice", "count", "criteria"]) if (!src[k]) fail(`missing "${k}"`);
if (!src.source?.title || !src.source?.href) fail("source needs title and href");

const uuid5 = uuid5From(UUID_NS);
const errors = [];
const seen = new Set();
const token = (id, where) => {
  if (!/^[A-Za-z_][\w.-]*$/.test(id ?? "")) errors.push(`${where}: "${id}" is not an OSCAL token`);
  else if (seen.has(id)) errors.push(`${where}: ${id} occurs twice`);
  seen.add(id);
};
let count = 0;
const groups = src.criteria.map((cat) => {
  token(cat.id, "category");
  if (!cat.title) errors.push(`${cat.id}: no title`);
  return {
    id: cat.id,
    class: "category",
    title: cat.title,
    groups: (cat.groups ?? []).map((g) => {
      token(g.id, cat.id);
      if (!g.title) errors.push(`${g.id}: no title`);
      return {
        id: g.id,
        class: "series",
        title: g.title,
        controls: (g.controls ?? []).map(([id, title]) => {
          token(id, g.id);
          if (!id?.startsWith(`${g.id}.`)) errors.push(`${id}: not in series ${g.id}`);
          if (!title) errors.push(`${id}: no title`);
          count++;
          return {
            id,
            class: "criterion",
            title,
            props: [{ name: "label", value: id }],
            parts: [
              {
                id: `${id}_smt`,
                name: "statement",
                prose: `The text of ${id} is not reproduced here; it is ${src.owner}'s. Read it, with its points of focus, in the source: ${src.source.title}.`,
              },
            ],
          };
        }),
      };
    }),
  };
});
if (count !== src.count) errors.push(`${count} criteria, but the source has ${src.count}`);
if (errors.length) fail(`${errors.length} error(s):\n  ${errors.join("\n  ")}`);

const out = {
  catalog: {
    uuid: uuid5(`catalog:${src.title}:${src.version}`),
    metadata: {
      title: src.title,
      "last-modified": src["last-modified"],
      version: src.version,
      "oscal-version": "1.2.3",
      props: [{ name: "text-reproduced", ns: NS, value: "none" }],
      links: [{ href: src.source.href, rel: "reference", text: src.source.title }],
      remarks: `Generated by grundschutz-worksheets tools/id-catalog.mjs. Do not edit by hand. ${src.notice}`,
    },
    groups,
    "back-matter": {
      resources: [
        {
          uuid: uuid5(`source:${src.source.href}`),
          title: src.source.title,
          citation: { text: `${src.owner}: ${src.source.title}`, links: [{ href: src.source.href, rel: "reference" }] },
          rlinks: [{ href: src.source.href }],
        },
      ],
    },
  },
};
process.stdout.write(JSON.stringify(out, null, 2) + "\n");
